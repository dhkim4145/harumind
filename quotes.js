// 오늘 요일에 맞는 글귀 반환 (0=월, 1=화, ..., 6=일)
function getTodayQuote(emotion) {
  const day = new Date().getDay(); // 0=일, 1=월, ..., 6=토
  const index = day === 0 ? 6 : day - 1; // 일요일=6, 월요일=0으로 변환
  return QUOTES[emotion]?.[index] || "오늘을 다 이해하지 못해도 괜찮습니다.";
}
